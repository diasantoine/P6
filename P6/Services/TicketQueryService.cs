using Microsoft.EntityFrameworkCore;
using P6.Data;
using P6.Dtos;

namespace P6.Services;

/// <summary>
/// One parameterized query instead of one query per case: in progress / resolved, for a product,
/// a version, a period and keywords are all the same query with different criteria.
/// </summary>
public class TicketQueryService
{
    private readonly NexaWorksContext _db;

    public TicketQueryService(NexaWorksContext db)
    {
        _db = db;
    }

    public async Task<List<TicketDto>> GetTicketsAsync(TicketFilter filter)
    {
        // Read-only query: no change tracking needed.
        var query = _db.Tickets
            .AsNoTracking()
            .Where(t => t.StatusId == filter.Status);

        // Each criterion is added only when it is filled. Nothing is sent to the database yet:
        // the query is still an IQueryable, translated to a single SQL statement at ToListAsync().
        if (!string.IsNullOrWhiteSpace(filter.Product))
        {
            query = query.Where(t => t.VersionOperatingSystem.Version.Product.Name == filter.Product);
        }

        if (!string.IsNullOrWhiteSpace(filter.Version))
        {
            query = query.Where(t => t.VersionOperatingSystem.Version.Number == filter.Version);
        }

        if (filter.From is not null)
        {
            query = query.Where(t => t.CreatedAt >= filter.From.Value);
        }

        if (filter.To is not null)
        {
            query = query.Where(t => t.CreatedAt <= filter.To.Value);
        }

        // One Where per keyword: the ticket must contain all of them (translated to LIKE '%word%').
        foreach (var keyword in filter.Keywords ?? [])
        {
            if (!string.IsNullOrWhiteSpace(keyword))
            {
                query = query.Where(t => t.Problem.Contains(keyword));
            }
        }

        // Projection: only the needed columns are read, the joins are generated by EF Core.
        return await query
            .OrderBy(t => t.CreatedAt)
            .Select(t => new TicketDto(
                t.Id,
                t.VersionOperatingSystem.Version.Product.Name,
                t.VersionOperatingSystem.Version.Number,
                t.VersionOperatingSystem.OperatingSystem.Name,
                t.Status.Label,
                t.CreatedAt,
                t.ResolvedAt,
                t.Problem,
                t.Resolution))
            .ToListAsync();
    }
}
